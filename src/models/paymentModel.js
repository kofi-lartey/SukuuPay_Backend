import mongoose from "mongoose";

import { nextReceiptNumber } from "../utils/receiptNumber.js";

const paymentSchema = new mongoose.Schema(
  {
    // ── Identity ──
    paymentId: {
      type: String,
      unique: true,
      trim: true,
      index: true,
    },

    /**
     * The parent's own reference for this payment, issued when the prompt is sent.
     *
     * Distinct from `paymentId` on purpose. `paymentId` is minted in the pre-save
     * hook, so it does not exist until the document is written — which makes it
     * useless as the handle a *client* holds while waiting, because a retry of the
     * initiate call cannot know it in advance. The portal polls
     * `GET /pay/:token/verify/:reference` every few seconds while the parent approves
     * on their handset, and needs a value that exists before the response is sent.
     *
     * So this is generated by the service at create time, returned to the parent,
     * and resolvable without a database scan. `sparse` because desk payments made
     * in the admin Payments screen never have one, and a non-sparse unique index
     * would carry a null for every one of them.
     */
    reference: {
      type: String,
      trim: true,
      default: null,
    },

    // ── References ──
    studentId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Student",
      required: true,
      index: true,
    },
    schoolId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "School",
      required: true,
      index: true,
    },
    parentId: {
      type: mongoose.Schema.Types.ObjectId,
      default: null,
    },

    // Set when the payment settles an installment on a payment plan; the
    // webhook uses it to apply the money to the right plan.
    paymentPlanId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "PaymentPlan",
      default: null,
      index: true,
    },

    /**
     * The payout this payment was collected for, once one has been approved.
     *
     * The write path is `updateMany`, which runs **without document validation** —
     * and a strict schema silently drops a path it does not declare on exactly that
     * operation. So the field has to exist here for the stamp to be queryable at
     * all; without it the batch's membership lived only in
     * `DisbursementBatch.paymentIds` and the reverse lookup was unavailable.
     *
     * Indexed because it is the anti-join for "has this payment already been
     * paid out?" — the query that stops a second batch claiming money already
     * committed to a school.
     */
    disbursementBatchId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "DisbursementBatch",
      default: null,
      index: true,
    },

    /**
     * Set on a reversal row; names the payment it reverses.
     *
     * **This field is why an over-refund is detectable at all.** Until it existed the
     * only way to ask "how much of this payment has already been given back" was to
     * scan every negative payment for the same student and parent and hope the
     * `description` still began with `"Refund:"` — which is a string convention, not
     * a relation. `refundPayment` checked `refundAmount > payment.amount` and
     * nothing else, so two refunds of 60% each both passed and the school was
     * refunded 20% more than was collected.
     *
     * A reversal is **not** marked by a status on the original: a partially refunded
     * payment stays `completed` (it is still partly real money), so the original row
     * cannot carry the running total. The relationship has to live on the child.
     *
     * Sparse and not required — most rows in this collection are ordinary payments
     * and never reverse anything, and a non-sparse index would carry a null entry for
     * every one of them.
     *
     * **No `index: true` here.** The index is declared once, in `schema.index()` below,
     * because that is where `sparse` lives. Declaring both makes Mongoose emit a
     * "Duplicate schema index" warning and keep the *first* definition — so the field's
     * bare `index: true` wins and `{ sparse: true }` is silently discarded, leaving a
     * full index that stores a null for every payment on the platform.
     */
    refundOfPaymentId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Payment",
      default: null,
    },

    // ── Payment details ──
    amount: {
      type: Number,
      required: true,
      // **No `min`**, because a refund row is written with a negative amount.
      //
      // `refundPayment` in payment.service.js records the reversal as its own
      // Payment with `amount: -refundAmount` — a deliberate design choice, so the
      // ledger stays additive and a full reversal shows up alongside the original
      // row that cancelled it. `min: 0` rejected that document at validation, so
      // `POST /payments/:paymentId/refund` failed with a 500 on *every* refund,
      // including partial ones. The invariant this field actually has is "a
      // payment is not zero", which is asserted below; the sign is meaningful and
      // carries the direction of the entry.
      validate: {
        validator: (value) => value !== 0,
        message: "A payment amount cannot be zero — use the status field to void a payment",
      },
      validate: {
        validator: (v) => Number.isInteger(v),
        message: "Amount must be an integer number of pesewas",
      },
    },
    currency: {
      type: String,
      default: "GHS",
      enum: ["GHS"],
    },
    status: {
      type: String,
      enum: ["pending", "processing", "completed", "failed", "cancelled", "refunded"],
      default: "pending",
      index: true,
    },
    paymentMethod: {
      type: String,
      enum: ["momo", "card", "bank_transfer", "cash"],
      default: "momo",
    },
    provider: {
      type: String,
      enum: ["arke", "mnotify", "manual", "mtn", "moolre"],
      default: "moolre",
      index: true,
    },

    // ── MTN MoMo specific fields ──
    mtnReferenceId: {
      type: String,
      default: null,
      index: true,
    },
    mtnFinancialTransactionId: {
      type: String,
      default: null,
      index: true,
    },
    mtnResponseCode: {
      type: String,
      default: null,
    },
    mtnResponseMessage: {
      type: String,
      default: null,
    },
    mtnStatusReason: {
      type: String,
      default: null,
    },

    // ── Moolre specific fields ──
    //
    // `moolreReference` is our own `Payment.reference`, echoed back by Moolre
    // on the callback. It is the join key for a callback that carries no
    // transaction id of its own.
    moolreReference: {
      type: String,
      default: null,
      index: true,
    },
    moolreTransactionId: {
      type: String,
      default: null,
      index: true,
    },
    // The network Moolre charged, stored in Moolre's own vocabulary (13 / 6 / 7)
    // because that is what comes back on the callback and on a status poll.
    moolreChannel: {
      type: String,
      default: null,
    },
    moolreResponseMessage: {
      type: String,
      default: null,
    },

    momoPhoneNumber: {
      type: String,
      default: null,
    },
    momoNetwork: {
      type: String,
      enum: ["MTN", "VODAFONE", "AIRTELTELIGO", "UNKNOWN"],
      default: "UNKNOWN",
    },

    // ── Description & metadata ──
    description: {
      type: String,
      trim: true,
      maxlength: 500,
    },
    invoiceNumber: {
      type: String,
      trim: true,
      maxlength: 50,
    },
    feesBreakdown: {
      type: [mongoose.Schema.Types.Mixed],
      default: [],
    },

    // ── Timestamps ──
    initiatedAt: {
      type: Date,
      default: Date.now,
    },
    completedAt: {
      type: Date,
      default: null,
    },
    failedAt: {
      type: Date,
      default: null,
    },
    refundedAt: {
      type: Date,
      default: null,
    },

    // ── Webhook / callback data ──
    webhookPayload: {
      type: mongoose.Schema.Types.Mixed,
      default: null,
    },
    webhookReceivedAt: {
      type: Date,
      default: null,
    },

    // ── Settlement ──
    // The stamp that makes a payment confirmation idempotent. A gateway retries
    // until it gets a 2xx, and the same "payment succeeded" callback routinely
    // arrives two or three times; without this claim each retry would run the
    // $inc on the student's totalPaid again and credit the parent multiple
    // times. Set atomically, before the balance updates, so two concurrent
    // retries cannot both win.
    settlement: {
      appliedAt: { type: Date, default: null },
      reference: { type: String, default: null },
    },

    // ── Receipt ──
    //
    // **No `unique: true` here.** The uniqueness is declared once, in
    // `schema.index()` below, because that is where the partial filter lives —
    // and declaring both makes Mongoose keep the *first* definition and
    // discard the second's options, which would throw the partial filter away
    // and leave the broken index in place.
    receiptNumber: {
      type: String,
      trim: true,
      default: null,
    },
    receiptGeneratedAt: {
      type: Date,
      default: null,
    },

    // ── Settlement notifications ──
    //
    // The claim that makes "tell the parent and the school" happen exactly once.
    //
    // It is taken the same way the settlement claim is — atomically, by a
    // conditional update, before anything is sent — because a gateway that is
    // not answered retries, and a provider that retries after a partial
    // failure would otherwise leave a parent with two "payment received"
    // messages for one payment. A family that is told twice is a family that
    // stops believing the school.
    //
    // `channels` records which channels actually delivered, so a school that
    // asks "did the receipt go out?" has an answer that is not a guess.
    notification: {
      sentAt: { type: Date, default: null },
      channels: { type: [String], default: [] },
    },

    // ── Audit ──
    createdBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },
    updatedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      default: null,
    },
    deletedAt: {
      type: Date,
      default: null,
      index: true,
    },
  },
  { timestamps: true }
);

// ── Indexes ──
paymentSchema.index({ schoolId: 1, status: 1 });
paymentSchema.index({ schoolId: 1, createdAt: -1 });
paymentSchema.index({ studentId: 1, status: 1 });
paymentSchema.index({ paymentPlanId: 1, status: 1 });

/*
 * The portal's polling lookup: `findOne({ reference })`.
 *
 * Unique, because two payments sharing a reference would make a parent's status
 * check resolve to an arbitrary one of them — and the parent is checking to find
 * out whether their money arrived.
 *
 * **Partial, and it has to be.** A desk payment recorded in the admin console
 * carries `reference: null`, and MongoDB's `sparse` option skips only a
 * *missing* field — an explicit `null` is indexed, and indexed as null. A
 * sparse unique index therefore means *one payment without a reference per
 * database*, and the second desk payment a bursar records dies on E11000 with
 * `keyValue: { reference: null }`. `partialFilterExpression` on the string type
 * is the index-level guarantee that only payments which actually carry a
 * reference take part in the uniqueness check.
 */
paymentSchema.index(
  { reference: 1 },
  { unique: true, partialFilterExpression: { reference: { $type: "string" } } }
);

/**
 * One receipt number per payment, and no two payments share one.
 *
 * **Partial, and it has to be.** `receiptNumber` is null for every payment that
 * has not settled, and a plain unique index treats a missing field as null for
 * uniqueness — so it means *one unreceipted payment per database*. The second
 * one to be inserted dies on E11000 with `keyValue: { receiptNumber: null }`,
 * which is what a parent's "Pay" button hit: a 500 on the one screen they had
 * to get past, and no way for the family to pay at all.
 *
 * `partialFilterExpression: { receiptNumber: { $type: "string" } }` keeps the
 * uniqueness guarantee for receipts and takes unreceipted payments out of it
 * entirely.
 */
paymentSchema.index(
  { receiptNumber: 1 },
  { unique: true, partialFilterExpression: { receiptNumber: { $type: "string" } } }
);

/*
 * The payout worklist: "every completed payment for this school that no batch has
 * claimed". A disbursement run is driven by this query, and it is the only read that
 * has to be fast on a school with tens of thousands of settled payments.
 */
paymentSchema.index({ schoolId: 1, status: 1, disbursementBatchId: 1 });

/*
 * "How much of this payment has already been given back."
 *
 * The over-refund guard's query. Rare — almost every payment is never refunded —
 * and therefore almost always a single-document lookup, so an index on a low-cardinality
 * field would only ever bloat the collection without being used.
 */
paymentSchema.index({ refundOfPaymentId: 1 }, { sparse: true });

// ── Pre-save hooks ──
// No `next` parameter: mongoose does not supply a callback to a pre-save hook,
// so declaring one would shadow an unrelated argument and throw on every save.
paymentSchema.pre("save", async function () {
  // Auto-generate paymentId if missing
  if (!this.paymentId) {
    const dateStr = new Date().toISOString().slice(0, 10).replace(/-/g, "");
    const random = Math.random().toString(36).substring(2, 8).toUpperCase();
    this.paymentId = `PAY-${dateStr}-${random}`;
  }

  // Auto-generate receipt number for completed payments
  //
  // From the atomic counter, not from a count of the school's receipts today.
  // The count was a read-then-write race: two payments settling in the same
  // moment read the same count, picked the same number, and one of them died
  // on the unique index — with the money already taken and the payment left
  // unsettled. `utils/receiptNumber.js` has the reasoning.
  if (this.status === "completed" && !this.receiptNumber) {
    this.receiptNumber = await nextReceiptNumber(this.schoolId);
    this.receiptGeneratedAt = new Date();
  }

  // Set completedAt when status changes to completed
  if (this.isModified("status") && this.status === "completed" && !this.completedAt) {
    this.completedAt = new Date();
  }

  // Set failedAt when status changes to failed
  if (this.isModified("status") && this.status === "failed" && !this.failedAt) {
    this.failedAt = new Date();
  }

  // Set refundedAt when status changes to refunded
  if (this.isModified("status") && this.status === "refunded" && !this.refundedAt) {
    this.refundedAt = new Date();
  }
});

// ── toJSON: strip sensitive fields ──
paymentSchema.set("toJSON", {
  virtuals: true,
  transform: (_doc, ret) => {
    delete ret.__v;
    delete ret.webhookPayload;
    return ret;
  },
});

export const Payment = mongoose.model("Payment", paymentSchema);